require('./local-only-browser.cjs');
const assert = require('assert'), fs = require('fs'), path = require('path'), vm = require('vm');
const { chromium } = require('playwright');
const { readFinalVocabulary } = require('./final-vocabulary');
const {file, rows} = readFinalVocabulary();
const ctx = {PropertiesService:{getScriptProperties:()=>({getProperty:()=> 'test-only'})}};
vm.createContext(ctx);vm.runInContext(fs.readFileSync('exam/sheet_backend.gs','utf8'),ctx);
const db = [Array.from(ctx.VOCABULARY_DB_HEADERS), ...rows.map(r=>Array.from(ctx.VOCABULARY_DB_HEADERS,k=>r[k]??''))];
ctx.SpreadsheetApp={getActiveSpreadsheet:()=>({getSheetByName:()=>({getDataRange:()=>({getValues:()=>db})})})};
const output=path.resolve('output/vocabulary-local-tests');fs.mkdirSync(output,{recursive:true});
(async()=>{
  const browser=await chromium.launch();
  try {
    for(const width of [390,1280]) {
      const page=await browser.newPage({viewport:{width,height:900}});
      const errors=[],apiCalls=[];let delaySearch=false;
      page.on('pageerror',e=>errors.push(e.message));
      await page.addInitScript(()=>localStorage.setItem('hub.delivery',JSON.stringify({url:'https://vocab-local.test/exec',token:'test-only'})));
      await page.route('https://vocab-local.test/**',async route=>{
        apiCalls.push(route.request().method()+' '+route.request().url());
        assert.strictEqual(route.request().method(),'GET','no staging, commit or other POST');
        const u=new URL(route.request().url()),parameter=Object.fromEntries(u.searchParams);
        assert.strictEqual(parameter.action,'listVocabularyDbV1');
        const result=ctx.handleListVocabularyDbV1_({parameter});
        if(delaySearch&&parameter.q==='molecule')await new Promise(resolve=>setTimeout(resolve,300));
        await route.fulfill({contentType:'application/javascript',body:parameter.callback?`${parameter.callback}(${JSON.stringify(result)})`:JSON.stringify(result)});
      });
      await page.goto('http://127.0.0.1:8765/teacher/vocabulary-db.html',{waitUntil:'networkidle'});
      assert.strictEqual(apiCalls.length,0,'initial local mode makes zero API calls even with credentials');
      await page.locator('#file').setInputFiles(file);
      await page.waitForFunction(()=>document.querySelector('#importMsg').textContent.includes('파일 검증 완료'));
      assert.strictEqual(await page.locator('#modeLabel').innerText(),'로컬 XLSX 검토 모드');
      assert((await page.locator('#modeHelp').innerText()).includes('새로고침'));
      const stats=await page.locator('#importStats').innerText();
      for(const value of ['3200','V1','V2','V3','V4','V5','800','600','200']) assert(stats.includes(value));
      for(const id of ['stage','commit','previewSet','createSet']) assert(await page.locator('#'+id).isDisabled(),id);
      assert.strictEqual(await page.locator('.row .actions button:enabled').count(),0);
      const ids=[];
      for(let n=1;n<=16;n++) {
        await page.waitForFunction(n=>document.querySelector('#pageInfo').textContent===`${n} / 16 페이지 · 전체 3200개`,n);
        assert.strictEqual(await page.locator('.row').count(),200);
        ids.push(...await page.locator('[data-sense]').evaluateAll(nodes=>nodes.map(x=>x.dataset.sense)));
        if(n<16)await page.locator('#nextPage').click();
      }
      assert.strictEqual(new Set(ids).size,3200);
      assert.deepStrictEqual([...ids].sort(),rows.map(r=>r.sense_id).sort());
      assert(await page.locator('#nextPage').isDisabled());
      await page.locator('#level').selectOption('V5');
      await page.waitForFunction(()=>document.querySelector('#pageInfo').textContent==='1 / 1 페이지 · 전체 200개');
      await page.locator('#level').selectOption('');
      await page.locator('#query').fill('molecule');
      await page.waitForFunction(()=>document.querySelectorAll('.row').length===1);
      assert((await page.locator('#words').innerText()).includes('molecule'));
      await page.locator('#query').fill('세포');
      assert((await page.locator('#words').innerText()).includes('세포'));
      await page.locator('#query').fill('');
      await page.locator('#scope').selectOption('archive');
      assert.strictEqual(await page.locator('.row').count(),0);
      await page.locator('#scope').selectOption('curriculum');
      await page.locator('#sort').selectOption('alphabetical');
      assert.strictEqual(await page.locator('.row').count(),200);
      const localAlphabetical=await page.locator('[data-sense]').evaluateAll(nodes=>nodes.map(x=>x.dataset.sense));
      assert.strictEqual(apiCalls.length,0,'all local filters and pages make zero API calls');
      assert((await page.locator('.row').first().innerText()).includes('뜻 순서'));
      assert(await page.locator('.row .score').first().isVisible());
      assert.strictEqual(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
      await page.screenshot({path:path.join(output,`local-xlsx-${width}.png`),fullPage:true});
      await page.locator('#serverMode').click();
      await page.waitForFunction(()=>document.querySelector('#pageInfo').textContent==='1 / 16 페이지 · 전체 3200개');
      assert.deepStrictEqual(await page.locator('[data-sense]').evaluateAll(nodes=>nodes.map(x=>x.dataset.sense)),localAlphabetical,'local and server ordering agree');
      await page.locator('#nextPage').click();
      await page.waitForFunction(()=>document.querySelector('#pageInfo').textContent.startsWith('2 / 16'));
      await page.locator('#prevPage').click();
      await page.waitForFunction(()=>document.querySelector('#pageInfo').textContent.startsWith('1 / 16'));
      await page.locator('#level').selectOption('V2');
      await page.waitForFunction(()=>document.querySelector('#pageInfo').textContent==='1 / 4 페이지 · 전체 800개');
      await page.locator('#nextPage').click();
      await page.waitForFunction(()=>document.querySelector('#pageInfo').textContent.startsWith('2 / 4'));
      const last=new URL(apiCalls[apiCalls.length-1].slice(4));
      assert.strictEqual(last.searchParams.get('level'),'V2');
      assert.strictEqual(last.searchParams.get('sort'),'alphabetical');
      assert.strictEqual(last.searchParams.get('scope'),'curriculum');
      await page.locator('#query').fill('no-such-word-xyz');
      await page.waitForFunction(()=>document.querySelector('#pageInfo').textContent==='1 / 1 페이지 · 전체 0개');
      await page.screenshot({path:path.join(output,`server-pagination-${width}.png`),fullPage:true});
      assert.strictEqual(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
      await page.locator('#level').selectOption('');
      delaySearch=true;
      await page.locator('#query').fill('molecule');
      await page.locator('#localMode').click();
      await page.locator('#query').fill('cell');
      await page.waitForTimeout(450);
      assert.strictEqual(await page.locator('#modeLabel').innerText(),'로컬 XLSX 검토 모드');
      assert(!(await page.locator('#words').innerText()).includes('molecule'),'late server response cannot replace local file rows');
      assert((await page.locator('#words').innerText()).includes('cell'));
      assert(await page.locator('#commit').isDisabled());
      assert(await page.locator('#createSet').isDisabled());
      const beforeInvalid=apiCalls.length;
      await page.locator('#file').setInputFiles({name:'invalid.xlsx',mimeType:'application/octet-stream',buffer:Buffer.from('not an XLSX workbook')});
      await page.waitForFunction(()=>document.querySelector('#importMsg').textContent.includes('ELAB_Import'));
      assert.strictEqual(await page.locator('.row').count(),0);
      assert.strictEqual(await page.locator('#importStats').innerText(),'');
      assert.strictEqual(apiCalls.length,beforeInvalid);
      await page.reload({waitUntil:'networkidle'});
      assert.strictEqual(await page.locator('#modeLabel').innerText(),'로컬 XLSX 검토 모드');
      assert.strictEqual(await page.locator('.row').count(),0,'file rows not persisted');
      assert.deepStrictEqual(errors,[]);
      await page.close();
    }
    console.log('vocabulary_db_xlsx_ui.test.js: final XLSX, 3200 unique IDs, zero local APIs, server paging, 390px and 1280px passed');
  }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});
